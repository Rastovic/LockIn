import 'dart:convert';
import 'dart:io';

/// Turns `assets/library_v1.json` into a Dart constant.
///
/// The JSON stays the editable source - it is what the content tests read and
/// what a writer edits. The generated Dart is what ships.
///
/// Generating rather than bundling keeps `tally_engine` free of Flutter: a pure
/// Dart package cannot declare a Flutter asset, and the alternative was either
/// duplicating the file into every app or making the engine depend on Flutter
/// to read its own content. Neither is worth it for forty rows that change
/// rarely.
///
/// Run: `dart run tool/generate_library.dart`
void main() {
  final source = File('assets/library_v1.json').readAsStringSync();
  final json = jsonDecode(source) as Map<String, Object?>;
  final items = (json['items'] as List).cast<Map<String, Object?>>();

  final buffer = StringBuffer()
    ..writeln('// GENERATED BY tool/generate_library.dart. DO NOT EDIT.')
    ..writeln('// Edit assets/library_v1.json and re-run the generator.')
    ..writeln("//")
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import '../library.dart';")
    ..writeln()
    ..writeln('/// The version of the library these items came from.')
    ..writeln('const libraryVersion = ${json['version']};')
    ..writeln()
    ..writeln('/// The shipped discipline library.')
    ..writeln('const shippedLibrary = <LibraryItem>[');

  for (final item in items) {
    final sticker = item['sticker'];
    buffer
      ..writeln('  LibraryItem(')
      ..writeln("    id: '${item['id']}',")
      ..writeln("    title: ${_dart(item['title'] as String)},")
      ..writeln('    category: LibraryCategory.${item['category']},')
      ..writeln('    minutes: ${item['minutes']},')
      ..writeln('    why: ${_dart(item['why'] as String)},')
      ..writeln('    phoneDown: ${item['phoneDown'] ?? false},')
      ..writeln(
        sticker == null ? '' : "    stickerId: '$sticker',",
      )
      ..writeln('  ),');
  }
  buffer.writeln('];');

  Directory('lib/src/generated').createSync(recursive: true);
  File('lib/src/generated/library_data.dart')
      .writeAsStringSync(buffer.toString().replaceAll('\n\n  ),', '\n  ),'));
  stdout.writeln('Wrote ${items.length} items.');
}

String _dart(String value) => "'${value.replaceAll("'", r"\'")}'";
